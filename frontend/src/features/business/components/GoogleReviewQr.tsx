"use client";

import { useEffect, useState } from "react";
import Image from "next/image";
import { ApiError } from "../../../lib/api/api-error";
import { getGoogleReviewQr } from "../services/business.service";
import styles from "./business.module.scss";

type QrState =
  | { status: "loading" }
  | { status: "empty" }
  | { status: "ready"; url: string }
  | { status: "error"; message: string };

export function GoogleReviewQr({
  configured,
}: {
  configured: boolean;
}) {
  const [attempt, setAttempt] = useState(0);
  const [state, setState] = useState<QrState>(
    configured ? { status: "loading" } : { status: "empty" },
  );

  useEffect(() => {
    if (!configured) {
      return;
    }

    const controller = new AbortController();
    let objectUrl: string | null = null;
    void getGoogleReviewQr(controller.signal)
      .then((image) => {
        if (controller.signal.aborted) {
          return;
        }
        objectUrl = URL.createObjectURL(image);
        setState({ status: "ready", url: objectUrl });
      })
      .catch((cause: unknown) => {
        if (controller.signal.aborted) {
          return;
        }
        setState({
          status: "error",
          message:
            cause instanceof ApiError
              ? cause.message
              : "The QR code could not be loaded.",
        });
      });

    return () => {
      controller.abort();
      if (objectUrl) {
        URL.revokeObjectURL(objectUrl);
      }
    };
  }, [configured, attempt]);

  return (
    <section className={styles.section} aria-labelledby="qr-title">
      <h2 id="qr-title">Google review QR code</h2>
      {state.status === "loading" ? (
        <p role="status">Loading your QR code…</p>
      ) : state.status === "empty" ? (
        <p className={styles.notice}>
          Configure a Google review URL to make its QR code available.
        </p>
      ) : state.status === "error" ? (
        <div>
          <p className={styles.error} role="alert">
            {state.message}
          </p>
          <button
            className={styles.button}
            type="button"
            onClick={() => {
              setState({ status: "loading" });
              setAttempt((value) => value + 1);
            }}
          >
            Retry QR code
          </button>
        </div>
      ) : (
        <div>
          <Image
            className={styles.qr}
            src={state.url}
            alt="QR code for the configured Google review link"
            width={256}
            height={256}
            unoptimized
          />
          <p className={styles.muted}>
            This image was generated by the Review Engine backend.
          </p>
          <a
            className={styles.link}
            href={state.url}
            download="google-review-qr.png"
          >
            Download QR code
          </a>
        </div>
      )}
    </section>
  );
}
